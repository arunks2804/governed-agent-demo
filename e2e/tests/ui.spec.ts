import { expect, test } from "@playwright/test";
import { USERS, resetDemo, runScenario, signIn } from "./helpers";

test.beforeEach(async ({ page }) => {
  await resetDemo(page);
});

test("identity selection: sign in, see tenant, sign out", async ({ page }) => {
  await signIn(page, USERS.nina);
  await expect(page.getByTestId("tenant")).toHaveText("northstar");
  await expect(page.getByTestId("run-order_summary")).toBeEnabled();
  await page.getByTestId("logout").click();
  await expect(page.getByTestId("login")).toBeVisible();
  await expect(page.getByTestId("run-order_summary")).toBeDisabled();
});

test("order summary returns own-tenant data through MCP", async ({ page }) => {
  await signIn(page, USERS.alice);
  await runScenario(page, "order_summary");
  await expect(page.getByTestId("outcome")).toHaveAttribute("data-outcome", "allowed");
  await expect(page.getByTestId("run-identity")).toContainText("alice@acme.example");
  await expect(page.getByTestId("origin-label")).toContainText("not generated by an LLM");
  await expect(page.getByTestId("sql")).toContainText("GROUP BY status");
  await expect(page.getByTestId("decision")).toContainText("ALLOW");
  await expect(page.getByTestId("decision")).toContainText("acme_reader");
  await expect(page.getByTestId("result-table")).toBeVisible();
  await expect(page.getByTestId("route").locator("li[data-state=allow]")).toHaveCount(5);
  await expect(page.getByTestId("enforcement-log")).toContainText("OPA policy");
});

test("SELECT * returns only Acme rows with RLS evidence", async ({ page }) => {
  await signIn(page, USERS.alice);
  await runScenario(page, "select_star");
  await expect(page.getByTestId("row-count")).toContainText("60 row(s)");
  await expect(page.getByTestId("rls-evidence")).toContainText("tenant_id = 'acme'::text");
  const tenants = await page.getByTestId("result-table").locator("tbody tr td:nth-child(2)").allTextContents();
  expect(new Set(tenants)).toEqual(new Set(["acme"]));
});

test("explicit cross-tenant query is denied by OPA before PostgreSQL", async ({ page }) => {
  await signIn(page, USERS.alice);
  await runScenario(page, "cross_tenant_explicit");
  await expect(page.getByTestId("outcome")).toHaveAttribute("data-outcome", "denied");
  await expect(page.getByTestId("outcome")).toContainText("OPA policy");
  await expect(page.getByTestId("decision")).toContainText("cross-tenant");
  await expect(page.getByTestId("route").locator("li", { hasText: "PostgreSQL" })).toHaveAttribute("data-state", "skipped");
});

