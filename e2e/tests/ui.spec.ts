test("prepared direct-DB script is blocked in the protected runner", async ({ page }) => {
  await signIn(page, USERS.alice);
  await runScenario(page, "direct_db_protected");
  await expect(page.getByTestId("outcome")).toHaveAttribute("data-outcome", "blocked");
  await expect(page.getByTestId("origin-badge")).toHaveText("prepared-bypass-test");
  await expect(page.getByTestId("bypass-table")).toContainText("resolve hostname 'postgres'");
  await expect(page.getByTestId("bypass-table")).toContainText("TCP 10.231.10.10:5432");
  await expect(page.getByTestId("outcome")).toContainText("every known database IP unreachable");
  await expect(page.getByTestId("route").locator("li", { hasText: "PostgreSQL (direct)" })).toHaveAttribute("data-state", "deny");
});

test("the same script succeeds in the labelled prompt-only runner", async ({ page }) => {
  await signIn(page, USERS.alice);
  test.skip(await page.getByTestId("run-direct_db_prompt_only").isDisabled(), "prompt-only overlay not running");
  await runScenario(page, "direct_db_prompt_only");
  await expect(page.getByTestId("outcome")).toHaveAttribute("data-outcome", "bypassed");
  await expect(page.getByTestId("outcome")).toContainText("INSECURE");
  await expect(page.getByTestId("outcome")).toContainText("acme, northstar");
});

test("OPA revocation from the policy console denies the next request; restore re-allows", async ({ page }) => {
  await signIn(page, USERS.alice);
  await page.getByTestId("revoke").click();
  await expect(page.getByTestId("policy-state")).toContainText("REVOKED");
  await runScenario(page, "order_summary");
  await expect(page.getByTestId("outcome")).toHaveAttribute("data-outcome", "denied");
  await expect(page.getByTestId("outcome")).toContainText("revoked");
  await page.getByTestId("restore").click();
  await expect(page.getByTestId("policy-state")).toContainText("granted");
  await runScenario(page, "order_summary");
  await expect(page.getByTestId("outcome")).toHaveAttribute("data-outcome", "allowed");
});

test("policy console cannot change another tenant's access", async ({ page }) => {
  await signIn(page, USERS.alice);
  const res = await page.request.post("/api/policy", {
    headers: { "X-Requested-With": "governed-ui" },
    data: { action: "revoke", tenant: "northstar" },
  });
  expect(res.status()).toBe(403);
});

