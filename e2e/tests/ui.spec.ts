for (const [id, text] of [["write_attempt", "write/DDL"], ["role_change", "role changes"]] as const) {
  test(`${id} is rejected by SQL validation`, async ({ page }) => {
    await signIn(page, USERS.alice);
    await runScenario(page, id);
    await expect(page.getByTestId("outcome")).toHaveAttribute("data-outcome", "denied");
    await expect(page.getByTestId("outcome")).toContainText("SQL validation");
    await expect(page.getByTestId("outcome")).toContainText(text);
    await expect(page.getByTestId("decision")).toContainText("OPA not consulted");
  });
}

