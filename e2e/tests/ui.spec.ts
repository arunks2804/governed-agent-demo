test("manual SQL via MCP and manual Python", async ({ page }) => {
  await signIn(page, USERS.nina);
  await page.getByRole("tab", { name: "SQL via MCP" }).click();
  await page.getByTestId("custom-input").fill("SELECT count(*) AS n FROM orders");
  await page.getByTestId("custom-submit").click();
  await expect(page.getByTestId("origin-badge")).toHaveText("manual");
  await expect(page.getByTestId("result-table")).toContainText("45");

  await page.getByRole("tab", { name: "Python" }).click();
  await page.getByTestId("custom-input").fill("print('hello from the sandbox')");
  await page.getByTestId("custom-submit").click();
  await expect(page.getByTestId("stdout")).toContainText("hello from the sandbox");
});

