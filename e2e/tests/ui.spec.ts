test("server error is shown (intercepted response - mocked)", async ({ page }) => {
  await signIn(page, USERS.alice);
  await page.route("**/api/run", (route) =>
    route.fulfill({ status: 503, contentType: "application/json",
                    body: JSON.stringify({ ok: false, error: "agent_unavailable", message: "agent service unavailable" }) }));
  await page.getByTestId("run-order_summary").click();
  await expect(page.getByTestId("run-error")).toContainText("agent service unavailable");
});

test("reset clears history and restores policy", async ({ page }) => {
  await signIn(page, USERS.alice);
  await page.getByTestId("revoke").click();
  await runScenario(page, "order_summary");
  await expect(page.getByTestId("history").locator("li")).toHaveCount(1);
  await page.getByTestId("reset").click();
  await expect(page.getByTestId("empty")).toContainText("Demo reset");
  await expect(page.getByTestId("history").locator("li")).toHaveCount(0);
  await expect(page.getByTestId("policy-state")).toContainText("granted");
});
