"""Every demo scenario, end to end through the real agent service.

Scenario plans are deterministic (scripted / prepared), so these tests never
depend on an LLM choosing to misbehave. Live-LLM tests are marked live_llm and
are optional.
"""

from __future__ import annotations

import json
from typing import Any

import httpx
import pytest

from conftest import AGENT_URL, EXPECTED_ROWS, USERS, auth, mint, secret

OTHER = {"acme": "northstar", "northstar": "acme"}


def tokens(tenant: str) -> dict[str, str]:
    sub = USERS[tenant]
    return {
        "agent": mint(sub, tenant, aud="governed-agent", ctx="agent"),
        "data_token": mint(sub, tenant, ctx="agent"),
        "runner_token": mint(sub, tenant, ctx="runner"),
    }


def run(who: str, timeout: float = 60, **body: Any) -> httpx.Response:
    t = tokens(who)
    return httpx.post(
        f"{AGENT_URL}/v1/run",
        timeout=timeout,
        headers=auth(t["agent"]),
        json={"data_token": t["data_token"], "runner_token": t["runner_token"], **body},
    )


def scenario(tenant: str, scenario_id: str) -> dict[str, Any]:
    response = run(tenant, mode="scenario", scenario_id=scenario_id)
    assert response.status_code == 200, response.text
    return response.json()


@pytest.mark.parametrize("tenant", ["acme", "northstar"])
def test_order_summary(tenant: str) -> None:
    rec = scenario(tenant, "order_summary")
    assert rec["outcome"] == "allowed"
    assert rec["origin"] == "scripted-scenario" and "not generated by an LLM" in rec["origin_label"]
    step = rec["steps"][0]
    assert step["executed_as"] == f"{tenant}_reader"
    assert sum(r[1] for r in step["output"]["rows"]) == EXPECTED_ROWS[tenant]


def test_select_star_rls() -> None:
    step = scenario("acme", "select_star")["steps"][0]
    assert {r[1] for r in step["output"]["rows"]} == {"acme"}
    assert step["output"]["rls_evidence"]


