# ------------------------------------------------------------ agent API auth


def test_agent_requires_valid_agent_token() -> None:
    t = tokens("acme")
    body = {
        "data_token": t["data_token"],
        "runner_token": t["runner_token"],
        "mode": "scenario",
        "scenario_id": "order_summary",
    }
    assert httpx.post(f"{AGENT_URL}/v1/run", json=body, timeout=10).status_code == 401
    # A data-service token is not accepted as an agent token (audience check).
    assert httpx.post(f"{AGENT_URL}/v1/run", json=body, headers=auth(t["data_token"]), timeout=10).status_code == 401


def test_agent_rejects_mismatched_identity_tokens() -> None:
    acme, northstar = tokens("acme"), tokens("northstar")
    response = httpx.post(
        f"{AGENT_URL}/v1/run",
        timeout=10,
        headers=auth(acme["agent"]),
        json={
            "data_token": northstar["data_token"],
            "runner_token": acme["runner_token"],
            "mode": "scenario",
            "scenario_id": "order_summary",
        },
    )
    assert response.status_code == 401
    assert "does not match" in response.json()["message"]


def test_agent_rejects_extra_fields() -> None:
    response = run("acme", mode="scenario", scenario_id="order_summary", tenant="northstar")
    assert response.status_code == 422


def test_runner_control_token_never_returned() -> None:
    blob = repr(scenario("acme", "python_via_mcp"))
    assert secret("runner_control_token") not in blob


# ------------------------------------------------------- optional: live LLM


@pytest.mark.live_llm
def test_live_llm_task_goes_through_governed_path() -> None:
    response = run("acme", timeout=300, mode="llm", task="How many orders do we have in each status?")
    if response.status_code == 503:
        pytest.skip(f"local LLM unavailable: {response.json()['message']}")
    rec = response.json()
    assert rec["origin"] == "live-llm"
    tool_steps = [s for s in rec["steps"] if s.get("kind") in ("mcp", "python")]
    assert tool_steps, "the model made no tool calls"
    executed = [s["executed_as"] for s in tool_steps if s.get("executed_as")]
    assert all(role == "acme_reader" for role in executed)
    for step in tool_steps:  # whatever the model generated, nothing ran as another tenant
        assert "northstar_reader" not in json.dumps(step.get("output", {}))
