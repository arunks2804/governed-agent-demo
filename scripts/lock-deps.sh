#!/usr/bin/env bash
# Resolve each requirements.in to a fully pinned requirements.txt inside the
# exact base image the services run on (so platform-specific wheels match).
set -euo pipefail
cd "$(dirname "$0")/.."
IMAGE=python:3.12.15-slim-bookworm
for dir in services/data_service services/mcp_server services/runner services/agent services/web tests; do
  echo "locking $dir"
  docker run --rm -v "$PWD/$dir:/w:ro" "$IMAGE" sh -c \
    'pip install -q --disable-pip-version-check --root-user-action=ignore -r /w/requirements.in >/dev/null && pip freeze --exclude pip --exclude setuptools --exclude wheel' \
    | { echo "# Generated by scripts/lock-deps.sh from requirements.in - do not edit."; sort -f; } >"$dir/requirements.txt"
done
